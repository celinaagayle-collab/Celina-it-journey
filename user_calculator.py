num1= int(input("Enter your first number: "))
num2= int (input("Enter your second number: "))
operation= input("choose +,-,*, or /: ")
if operation== "+":
    print (num1+num2)
elif operation== "-":
    print (num1-num2)
elif operation== "*":
    print (num1*num2)
elif operation== "/": 
    print (num1/num2)
else:
    print ("invalid operation")

    

